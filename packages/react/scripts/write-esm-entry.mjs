#!/usr/bin/env node
/* eslint-disable no-console -- command-line script: its output is the report. */
/**
 * Writes `lib/index.mjs`, the facade's ESM entry (decision D6), after rollup has built the single CommonJS
 * implementation in `lib/`.
 *
 * The facade follows core's pattern (one CJS implementation, a thin ESM wrapper) with the peer binding of
 * `@pixi-react-provisional/pixi-8`: pixi.js ships separate ESM and CJS builds, so each entry binds the Pixi 8 adapter
 * its own module system loads, while both load the one implementation module `lib/bind.js`:
 *
 *   lib/index.js    require('@pixi-react-provisional/pixi-8'), then bindFacade() (built from src/index.ts)
 *   lib/index.mjs   import * as pixi8 from '@pixi-react-provisional/pixi-8', then the same bindFacade() of lib/bind.js
 *
 * `bindFacade` keeps one facade (one default runtime) per adapter class, so ESM and CJS consumers that share a
 * pixi.js instance share the default runtime. The wrapper lists the export names explicitly, read from the built
 * CJS entry, and the build fails if the bound facade lacks one of them.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const packageDir = process.cwd();
const require = createRequire(join(packageDir, 'package.json'));
const lib = join(packageDir, 'lib');

const names = Object.keys(require(join(lib, 'index.js'))).filter((name) => name !== '__esModule' && name !== 'default').sort();
const bound = Object.keys(require(join(lib, 'bind.js')).bindFacade(require('@pixi-react-provisional/pixi-8')));
const missing = names.filter((name) => !bound.includes(name));

if (missing.length)
{
    throw new Error(`The CJS entry exports ${missing.join(', ')}, which bindFacade() does not provide.`);
}

writeFileSync(join(lib, 'index.mjs'), [
    '// Generated by scripts/write-esm-entry.mjs: the ESM entry binds the single CJS implementation (lib/bind.js) to the',
    '// Pixi 8 adapter that `import` loads (D6).',
    'import * as pixi8 from \'@pixi-react-provisional/pixi-8\';',
    'import implementation from \'./bind.js\';',
    '',
    'const facade = implementation.bindFacade(pixi8);',
    '',
    `export const {\n${names.map((name) => `    ${name},`).join('\n')}\n} = facade;`,
    '',
].join('\n'));

console.log(`${packageDir}: lib/index.mjs re-exports ${names.length} bound names (${names.join(', ')})`);
