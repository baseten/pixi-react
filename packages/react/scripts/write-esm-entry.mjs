#!/usr/bin/env node
/* eslint-disable no-console -- command-line script: its output is the report. */
/**
 * Writes `lib/index.mjs`, the facade's ESM entry (decision D6), after rollup has built the single CommonJS
 * implementation in `lib/`.
 *
 * The facade follows core's pattern (one CJS implementation, a thin ESM wrapper) with the peer binding of the Pixi 8
 * adapter: pixi.js ships separate ESM and CJS builds, so each entry binds the pixi.js module its own module system
 * loads, while both load the one implementation module `lib/bind.js` (and, through it, the bundled adapters in
 * `lib/adapters.js`):
 *
 *   lib/index.js    require('pixi.js'), then bindFacade(bindPixi(pixi)) (built from src/index.ts)
 *   lib/index.mjs   import * as pixi from 'pixi.js', then the same bindFacade(bindPixi(pixi)) of lib/bind.js
 *
 * `bindPixi` keeps one bound Pixi 8 adapter per Pixi instance and `bindFacade` one facade (one default runtime) per
 * adapter class, so ESM and CJS consumers that share a pixi.js instance share the default runtime. The wrapper lists
 * the export names explicitly, read from the built CJS entry, and the build fails if the bound facade lacks one.
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const packageDir = process.cwd();
const require = createRequire(join(packageDir, 'package.json'));
const lib = join(packageDir, 'lib');

const names = Object.keys(require(join(lib, 'index.js'))).filter((name) => name !== '__esModule' && name !== 'default').sort();
const implementation = require(join(lib, 'bind.js'));
const bound = Object.keys(implementation.bindFacade(implementation.bindPixi(require('pixi.js'))));
const missing = names.filter((name) => !bound.includes(name));

if (missing.length)
{
    throw new Error(`The CJS entry exports ${missing.join(', ')}, which bindFacade() does not provide.`);
}

writeFileSync(join(lib, 'index.mjs'), [
    '// Generated by scripts/write-esm-entry.mjs: the ESM entry binds the single CJS implementation (lib/bind.js, with',
    '// the bundled adapters) to the pixi.js module that `import` loads (D6).',
    'import * as pixi from \'pixi.js\';',
    'import implementation from \'./bind.js\';',
    '',
    'const facade = implementation.bindFacade(implementation.bindPixi(pixi));',
    '',
    `export const {\n${names.map((name) => `    ${name},`).join('\n')}\n} = facade;`,
    '',
].join('\n'));

console.log(`${packageDir}: lib/index.mjs re-exports ${names.length} bound names (${names.join(', ')})`);
